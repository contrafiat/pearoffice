// Expo config plugin: keep PearOffice's store out of Google's CLOUD backup,
// while still allowing a direct phone-to-phone transfer. From PearPetal.
//
// The worklet keeps everything under <files>/pearoffice (mobile/App.js passes
// FileSystem.documentDirectory as dataDir): the files, their keys and the
// identity seed behind the recovery phrase. Android's Auto Backup is on by
// default, so without this all of it could be copied to the person's Google
// Drive, while PearOffice promises no servers and no cloud.
//
// Android 12+ configures cloud backup and device-to-device transfer
// separately: cloud backup excludes the store, a direct move to a new phone
// keeps it (the person's own devices, as with device linking). Android 11 and
// lower has one set of rules, so there the exclusion also covers transfer.

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins')
const fs = require('fs')
const path = require('path')

// The worklet's folder under the files directory (`domain="file"`, which is
// what expo maps documentDirectory to).
const STORE_DIR = 'pearoffice'

// Android 12+ (API 31+): cloud backup and device transfer configured separately.
const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-exclusion.js - do not edit by hand. -->
<data-extraction-rules>
  <cloud-backup>
    <!-- PearOffice's files and keys never go to Google's cloud. -->
    <exclude domain="file" path="${STORE_DIR}" />
  </cloud-backup>
  <device-transfer>
    <!-- A direct phone-to-phone move stays on the user's own devices, which is
         the same trust boundary as device linking. Everything included. -->
  </device-transfer>
</data-extraction-rules>
`

// Android 11 and lower: one set of rules for every backup mode.
const BACKUP_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-exclusion.js - do not edit by hand. -->
<full-backup-content>
  <exclude domain="file" path="${STORE_DIR}" />
</full-backup-content>
`

module.exports = function withAndroidBackupExclusion (config) {
  // 1. Write both rule files into res/xml.
  config = withDangerousMod(config, ['android', (cfg) => {
    const resXml = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml')
    fs.mkdirSync(resXml, { recursive: true })
    fs.writeFileSync(path.join(resXml, 'data_extraction_rules.xml'), DATA_EXTRACTION_RULES)
    fs.writeFileSync(path.join(resXml, 'backup_rules.xml'), BACKUP_RULES)
    return cfg
  }])

  // 2. Point the manifest at them. allowBackup stays true on purpose: the rules
  //    above already exclude the one thing that must not leave the device, and
  //    keeping backup on means a user's settings still restore.
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0]
    if (!app) throw new Error('with-android-backup-exclusion: no <application> in the manifest')
    app.$['android:dataExtractionRules'] = '@xml/data_extraction_rules'
    app.$['android:fullBackupContent'] = '@xml/backup_rules'
    app.$['android:allowBackup'] = 'true'
    return cfg
  })
}
